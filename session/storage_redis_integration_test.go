const (
	redisAddressEnv       = "PITAYA_INTEGRATION_REDIS_ADDR"
	redisOwnerKeyEnv      = "PITAYA_INTEGRATION_REDIS_OWNER_KEY"
	redisOwnerTokenEnv    = "PITAYA_INTEGRATION_REDIS_OWNER_TOKEN"
	redisSessionUIDEnv    = "PITAYA_INTEGRATION_SESSION_UID"
	integrationProofEnv   = "PITAYA_INTEGRATION_PROOF_PATH"
	integrationProofToken = "PITAYA_INTEGRATION_PROOF_TOKEN"
)

func requiredEnv(t *testing.T, name string) string {
	t.Helper()
	value, ok := os.LookupEnv(name)
	require.Truef(t, ok, "%s must be set by the integration harness", name)
	require.NotEmptyf(t, value, "%s must not be empty", name)
	return value
}

func requireLiteralLoopbackAddress(t *testing.T, address string) {
	t.Helper()
	host, portText, err := net.SplitHostPort(address)
	require.NoError(t, err, "Redis address must be a literal loopback host:port")
	require.Equal(t, "127.0.0.1", host, "Redis address must use literal IPv4 loopback")
	require.NotEmpty(t, portText)
	require.NotEqual(t, "0", portText)
	require.NotEqual(t, "0", portText[:1], "Redis port must not have a leading zero")
	port, err := strconv.Atoi(portText)
	require.NoError(t, err)
	require.GreaterOrEqual(t, port, 1)
	require.LessOrEqual(t, port, 65535)
	require.Equal(t, address, net.JoinHostPort(host, strconv.Itoa(port)))
}

func registerIntegrationProof(t *testing.T, path, token string) {
	t.Helper()
	require.True(t, filepath.IsAbs(path), "integration proof path must be absolute")
	_, err := os.Lstat(path)
	require.True(t, os.IsNotExist(err), "integration proof path must not already exist")

	t.Cleanup(func() {
		if t.Failed() || t.Skipped() {
			return
		}
		file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
		if err != nil {
			t.Errorf("create integration proof: %v", err)
			return
		}
		if _, err := fmt.Fprintln(file, token); err != nil {
			t.Errorf("write integration proof: %v", err)
		}
		if err := file.Close(); err != nil {
			t.Errorf("close integration proof: %v", err)
		}
	})
}

func TestFlushFrontendDataRedisRoundTrip(t *testing.T) {
	address := requiredEnv(t, redisAddressEnv)
	requireLiteralLoopbackAddress(t, address)

	ownerKey := requiredEnv(t, redisOwnerKeyEnv)
	ownerToken := requiredEnv(t, redisOwnerTokenEnv)
	sessionUID := requiredEnv(t, redisSessionUIDEnv)
	_, err := uuid.Parse(sessionUID)
	require.NoError(t, err, "session UID must be a UUID generated by the harness")
	require.Equal(t, uuid.MustParse(sessionUID).String(), sessionUID)

	proofPath := requiredEnv(t, integrationProofEnv)
	proofToken := requiredEnv(t, integrationProofToken)
	registerIntegrationProof(t, proofPath, proofToken)

	client := redis.NewClient(&redis.Options{
		Addr:            address,
		MaxRetries:      -1,
		MinRetryBackoff: -1,
		MaxRetryBackoff: -1,
		DialTimeout:     2 * time.Second,
		ReadTimeout:     2 * time.Second,
		WriteTimeout:    2 * time.Second,
		PoolTimeout:     2 * time.Second,
	})
	t.Cleanup(func() {
		if err := client.Close(); err != nil {
			t.Errorf("close Redis client: %v", err)
		}
	})

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	require.NoError(t, client.Ping(ctx).Err())

	actualOwnerToken, err := client.Get(ctx, ownerKey).Result()
	require.NoError(t, err, "read Redis ownership sentinel")
	require.Equal(t, ownerToken, actualOwnerToken, "Redis ownership sentinel mismatch")
	ownerTTL, err := client.PTTL(ctx, ownerKey).Result()
	require.NoError(t, err)
	require.Greater(t, ownerTTL, time.Duration(0), "ownership sentinel must be short-lived")
	require.LessOrEqual(t, ownerTTL, 2*time.Minute)

	sessionKey := "pit:u:" + sessionUID + ":"
	require.NotEqual(t, ownerKey, sessionKey)
	exists, err := client.Exists(ctx, sessionKey).Result()
	require.NoError(t, err)
	require.Zero(t, exists, "harness-owned session key must not pre-exist")
	t.Cleanup(func() {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cleanupCancel()
		deleted, err := client.Del(cleanupCtx, sessionKey).Result()
		if err != nil {
			t.Errorf("delete exact integration session key: %v", err)
			return
		}
		if deleted != 1 {
			t.Errorf("deleted %d keys, want exactly one integration session key", deleted)
		}
	})

	pool := session.NewSessionPool()
	pool.SetClusterCache(session.NewRedisCache(client, time.Minute))
	sess, isNew := pool.NewSession(nil, true, sessionUID)
	require.True(t, isNew)
	sess.SetFrontendData("frontend-1", 42)
	sess.SetIP("192.0.2.1")
	require.NoError(t, sess.SetData(map[string]interface{}{"coins": 7}))
	require.NoError(t, sess.FlushFrontendData())

	fields, err := client.HGetAll(ctx, sessionKey).Result()
	require.NoError(t, err)
	require.Equal(t, map[string]string{
		"o":  "1",
		"f":  "frontend-1",
		"s":  "42",
		"ip": "192.0.2.1",
		"u":  `{"coins":7}`,
	}, fields, "Redis hash must contain exactly the public session payload")
}
